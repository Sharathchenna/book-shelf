/**
 * The deployed Worker: OpenNext's generated handler for the site, plus
 * - an edge cache for visitors' page views (the pages render from D1 on every request otherwise), and
 * - the nightly Goodreads sync, which calls the site's own /api/sync route (code in lib/sync.ts).
 */

type Handler = { fetch: (request: Request, env: CloudflareEnv, ctx: ExecutionContext) => Promise<Response> };

// Imported on first use, not at startup: a cached page is answered before the site's large
// bundle is evaluated, which keeps cold starts cheap.
let site: Promise<Handler> | undefined;
// @ts-expect-error Generated by `opennextjs-cloudflare build`.
const loadSite = () => (site ??= import("./.open-next/worker.js").then((m) => m.default as Handler));

/** Pages that look the same to every visitor (the owner's controls load in the browser). */
const SHARED_PAGES = new Set(["/", "/articles", "/papers", "/newsletters", "/tweets"]);
/** Long enough to absorb bursts and cold starts; short enough that a sync shows up soon. */
const VISITOR_TTL_SECONDS = 60;

/**
 * A plain page load by a visitor. Not the signed-in owner (who always gets a fresh render, so
 * their changes show at once), and not Next's client-side navigation or prefetch requests,
 * whose responses differ from the HTML for the same URL.
 */
function sharedPageView(request: Request, url: URL): boolean {
  if (request.method !== "GET" || !SHARED_PAGES.has(url.pathname)) return false;
  if ((request.headers.get("cookie") ?? "").includes("shelf_session=")) return false;
  for (const name of request.headers.keys()) if (name === "rsc" || name.startsWith("next-router")) return false;
  return (request.headers.get("accept") ?? "").includes("text/html");
}

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    if (!sharedPageView(request, url)) return (await loadSite()).fetch(request, env, ctx);

    // The page is the same whatever its query (?book=… and ?q=… are read in the browser).
    const key = new Request(`${url.origin}${url.pathname}`, { headers: { accept: "text/html" } });
    const cache = (caches as unknown as { default: Cache }).default;
    const hit = await cache.match(key);
    if (hit) {
      const response = new Response(hit.body, hit);
      // Browsers always come back here: the edge copy is what's short-lived.
      response.headers.set("cache-control", "private, no-cache");
      response.headers.set("x-edge-cache", "hit");
      return response;
    }

    const response = await (await loadSite()).fetch(request, env, ctx);
    if (response.status === 200) {
      const copy = new Response(response.clone().body, response);
      copy.headers.set("cache-control", `public, max-age=${VISITOR_TTL_SECONDS}`);
      ctx.waitUntil(cache.put(key, copy));
    }
    return response;
  },

  async scheduled(_controller, env, ctx) {
    const request = new Request("https://cron.internal/api/sync", {
      method: "POST",
      // The route accepts the session secret as proof the call comes from this Worker.
      headers: { authorization: `Bearer ${env.SESSION_SECRET}` },
    });
    const res = await (await loadSite()).fetch(request, env, ctx);
    console.log(`Goodreads sync: ${res.status} ${await res.text()}`);
  },
} satisfies ExportedHandler<CloudflareEnv>;
